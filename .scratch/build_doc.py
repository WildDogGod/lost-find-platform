def strip_unused_media(path):
    """删除文档中已不再被引用的图片部件（原文档遗留的 6 张旧图）。"""
    tmp = path + ".tmp"
    with zipfile.ZipFile(path) as zin:
        names = zin.namelist()
        doc_xml = zin.read("word/document.xml").decode("utf-8")
        used = set(re.findall(r'r:(?:embed|link|id)="([^"]+)"', doc_xml))
        for n in names:
            if n.startswith("word/") and n.endswith(".xml") and n != "word/document.xml":
                try:
                    used |= set(re.findall(r'r:(?:embed|link|id)="([^"]+)"',
                                           zin.read(n).decode("utf-8", "ignore")))
                except KeyError:
                    pass
        rels_name = "word/_rels/document.xml.rels"
        rels = zin.read(rels_name).decode("utf-8")
        pattern = r"<Relationship\b[^>]*?/?>"
        drop_media, drop_rids = [], set()
        for m in re.finditer(pattern, rels):
            tag = m.group(0)
            rid = re.search(r'Id="([^"]+)"', tag).group(1)
            tgt = re.search(r'Target="([^"]+)"', tag).group(1)
            if tgt.startswith("media/") and rid not in used:
                drop_media.append("word/" + tgt)
                drop_rids.add(rid)
        new_rels = re.sub(
            pattern,
            lambda m: "" if re.search(r'Id="([^"]+)"', m.group(0)).group(1) in drop_rids
            else m.group(0),
            rels,
        )
        drop_set = set(drop_media)
        print("将删除未引用图片部件:", sorted(drop_set))
        with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
            for n in names:
                if n in drop_set:
                    continue
                data = zin.read(n)
                if n == rels_name:
                    data = new_rels.encode("utf-8")
                zout.writestr(n, data)
    os.replace(tmp, path)


